// tests/gemini-client.test.mjs
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { getGeminiStatus, transcribeWithGemini, notesToSimpleMidi, saveResultManifest, getGeminiConfig, updateGeminiConfig, getChordTones, pingGeminiConnection } from '../lib/gemini-client.mjs';
import { autoSheetEngine } from '../lib/auto-sheet-engine.mjs';

test('getGeminiStatus returns connection info without revealing secrets', () => {
  const status = getGeminiStatus();
  assert.equal(typeof status.configured, 'boolean');
  assert.equal(status.model, 'gemini-3.8-flash');
  assert.equal(status.provider, 'Google Gemini');
  assert.ok(Array.isArray(status.supportedFormats));
  assert.ok(status.supportedFormats.includes('wav'));
  assert.ok(status.supportedFormats.includes('midi'));
  assert.equal(status.exportFormat, 'MusicXML 4.0 (score-partwise)');

  // Critical: Never expose any raw API key string
  const jsonStr = JSON.stringify(status);
  assert.equal(jsonStr.includes('AIza'), false);
  assert.equal(jsonStr.includes('apiKey'), false);
});

test('notesToSimpleMidi generates valid monophonic standard MIDI file with MThd and MTrk', () => {
  const sampleNotes = [
    { midi: 60, beats: 1 },
    { midi: 64, beats: 1 },
    { midi: 67, beats: 2 },
    { midi: null, beats: 1 },
    { midi: 72, beats: 3 }
  ];

  const midiBuf = notesToSimpleMidi(sampleNotes, 90);
  assert.ok(Buffer.isBuffer(midiBuf));
  assert.ok(midiBuf.length >= 22);

  // MThd header check
  assert.equal(midiBuf.slice(0, 4).toString('ascii'), 'MThd');
  // MTrk track chunk check
  assert.equal(midiBuf.slice(14, 18).toString('ascii'), 'MTrk');
});

test('transcribeWithGemini converts song structure and audio into verified MusicXML 4.0 and manifest', async () => {
  const song = {
    id: 'nang-tho-test',
    title: 'Nàng Thơ',
    composer: 'Hoàng Dũng',
    key: 'C',
    content: '[C]Em ngày em đánh rơi nụ cười vào anh [Am]Có nghe mùa thu [F]vừa ghé qua [G]bậc thềm'
  };

  const result = await transcribeWithGemini({
    song,
    bpm: 85,
    rights: 'owned'
  });

  assert.ok(result.jobId);
  assert.equal(result.status, 'ai_draft');
  assert.equal(result.manifest.status, 'ai_draft');
  assert.equal(result.manifest.verified, false);
  assert.ok(result.confidence >= 0.8);
  assert.ok(result.notes.length >= 8);

  // Validate MusicXML 4.0 content
  assert.ok(result.musicxml.includes('score-partwise'));
  assert.ok(result.musicxml.includes('<work-title>Nàng Thơ</work-title>'));
  assert.ok(result.musicxml.includes('<divisions>2</divisions>'));
  assert.ok(result.musicxml.includes('<measure number="1">'));

  // Validate manifest conformity with tools/auto_sheet_ai.py
  assert.ok(result.manifest.generated_at);
  assert.equal(result.manifest.midi, 'notes.mid');
  assert.equal(result.manifest.musicxml, 'score.musicxml');
  assert.equal(result.manifest.review_required, true);
});

test('autoSheetEngine.importManifest correctly loads manifest generated by AI worker', () => {
  const testJobId = 'test-job-manifest-123';
  const notes = [{ midi: 60, beats: 1 }, { midi: 62, beats: 1 }, { midi: 64, beats: 2 }];
  const musicxml = '<?xml version="1.0" encoding="utf-8"?><score-partwise version="4.0"><part id="P1"><measure number="1"><note><pitch><step>C</step><octave>4</octave></pitch><duration>2</duration><type>quarter</type></note></measure></part></score-partwise>';

  const manifest = saveResultManifest({
    jobId: testJobId,
    songId: 'nang-tho',
    title: 'Nàng Thơ',
    rights: 'owned',
    notes,
    musicxml,
    confidence: 0.95
  });

  assert.equal(manifest.job_id, testJobId);
  const manifestPath = path.resolve('.goc-hop-am-ai', 'results', testJobId, 'manifest.json');
  assert.ok(fs.existsSync(manifestPath));

  const imported = autoSheetEngine.importManifest(manifestPath);
  assert.equal(imported.manifest.job_id, testJobId);
  assert.equal(imported.manifest.song_id, 'nang-tho');
  assert.ok(imported.musicxml.includes('score-partwise'));
});

test('getGeminiConfig and updateGeminiConfig manage AI sheet configuration correctly', () => {
  const currentCfg = getGeminiConfig();
  assert.equal(currentCfg.model, 'gemini-3.8-flash');
  assert.equal(typeof currentCfg.polyphonicAccompaniment, 'boolean');

  const updated = updateGeminiConfig({
    mode: 'polyphonic_piano',
    quantizationGrid: 0.25,
    polyphonicAccompaniment: false
  });

  assert.equal(updated.mode, 'polyphonic_piano');
  assert.equal(updated.quantizationGrid, 0.25);
  assert.equal(updated.polyphonicAccompaniment, false);

  // Restore defaults
  updateGeminiConfig({
    mode: 'melody_and_chords',
    quantizationGrid: 0.5,
    polyphonicAccompaniment: true
  });
});

test('getChordTones generates harmonic triads and bass notes accurately', () => {
  const cMaj = getChordTones('C');
  assert.deepEqual(cMaj, [48, 52, 55]); // C3 (48), E3 (52), G3 (55)

  const aMin = getChordTones('Am');
  assert.deepEqual(aMin, [57, 60, 64]); // A3 (57), C4 (60), E4 (64)

  const g7 = getChordTones('G7');
  assert.deepEqual(g7, [55, 59, 62, 65]); // G3 (55), B3 (59), D4 (62), F4 (65)

  const fMaj = getChordTones('F');
  assert.deepEqual(fMaj, [53, 57, 60]); // F3 (53), A3 (57), C4 (60)
});

